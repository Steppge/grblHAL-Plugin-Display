"""Large clock font for LVGL 9 from a TTF, without Node (lv_font_conv): Pillow renders the glyphs.

    python clockfont.py

Writes ../src/font_clock_120.c: Montserrat Medium (fonts/Montserrat-Medium.ttf, SIL Open Font License,
fonts/OFL-Montserrat.txt), 120 px, 4 bits per pixel, only "0"-"9" and ":" (U+0030-U+003A, one range).
The clock on the dimmed screen used the 48 px font zoomed 2.5 times; the zoom was computed in software on
every redraw and loaded the PSRAM (video underruns). A real 120 px font only copies finished glyphs.
"""

import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "fonts", "Montserrat-Medium.ttf")
OUT = os.path.join(HERE, "..", "src", "font_clock_120.c")
NAME = "font_clock_120"
SIZE = 120
FIRST, LAST = 0x30, 0x3A        # "0" .. ":"


def glyph(font, ch):
    """Bitmap (4 bpp, rows packed without padding, high nibble first) and the LVGL glyph metrics."""
    # render on a large canvas with the pen at (ox, oy) on the baseline, then measure the ink
    ox, oy = SIZE, 2 * SIZE
    canvas = Image.new("L", (4 * SIZE, 4 * SIZE), 0)
    ImageDraw.Draw(canvas).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    l, t, r, b = canvas.getbbox()
    w, h = r - l, b - t
    img = canvas.crop((l, t, r, b))
    l, b = l - ox, b - oy                            # left bearing, bottom relative to the baseline (y down)
    px = [(v + 8) // 17 for v in img.tobytes()]      # 0..255 -> 0..15
    data = bytearray()
    for i in range(0, len(px), 2):
        hi = px[i]
        lo = px[i + 1] if i + 1 < len(px) else 0
        data.append(hi << 4 | lo)
    adv = round(font.getlength(ch) * 16)
    return data, dict(adv_w=adv, box_w=w, box_h=h, ofs_x=l, ofs_y=-b)


def main():
    font = ImageFont.truetype(TTF, SIZE)
    ascent, descent = font.getmetrics()

    bitmap = bytearray()
    dsc = []
    lines = []
    for cp in range(FIRST, LAST + 1):
        ch = chr(cp)
        data, m = glyph(font, ch)
        m["bitmap_index"] = len(bitmap)
        dsc.append(m)
        lines.append(f'    /* U+{cp:04X} "{ch}" */')
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ",")
        bitmap += data

    out = []
    out.append("/* Generated by tools/clockfont.py, do not edit.")
    out.append(f" * Montserrat Medium {SIZE} px, 4 bpp, U+{FIRST:04X}-U+{LAST:04X} (\"0\"-\"9\", \":\"), {len(bitmap)} bytes.")
    out.append(" * Font: SIL Open Font License, see tools/fonts/OFL-Montserrat.txt */")
    out.append("")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    out += lines
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 reserved */,")
    for m in dsc:
        out.append("    {{.bitmap_index = {bitmap_index}, .adv_w = {adv_w}, .box_w = {box_w}, .box_h = {box_h}, "
                   ".ofs_x = {ofs_x}, .ofs_y = {ofs_y}}},".format(**m))
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    out.append(f"    {{.range_start = {FIRST}, .range_length = {LAST - FIRST + 1}, .glyph_id_start = 1,")
    out.append("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}")
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap,")
    out.append("    .glyph_dsc = glyph_dsc,")
    out.append("    .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL,")
    out.append("    .kern_scale = 0,")
    out.append("    .cmap_num = 1,")
    out.append("    .bpp = 4,")
    out.append("    .kern_classes = 0,")
    out.append("    .bitmap_format = 0,")
    out.append("};")
    out.append("")
    out.append(f"const lv_font_t {NAME} = {{")
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append(f"    .line_height = {ascent + descent},")
    out.append(f"    .base_line = {descent},")
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append(f"    .underline_position = {-SIZE // 12},")
    out.append(f"    .underline_thickness = {max(1, SIZE // 24)},")
    out.append("    .dsc = &font_dsc,")
    out.append("};")
    out.append("")

    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{os.path.normpath(OUT)}: {LAST - FIRST + 1} glyphs, {len(bitmap)} bytes, line height {ascent + descent}")


if __name__ == "__main__":
    main()
