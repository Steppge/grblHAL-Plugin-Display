# PlatformIO pre-build script of a display project (esp32s3/, esp32p4/):
# ../esp32common/web/index.html -> <project>/src/web_index.h (gzipped byte array for web.cpp)

Import("env")

import gzip
import os

src = os.path.join(env["PROJECT_DIR"], "..", "esp32common", "web", "index.html")
dst = os.path.join(env["PROJECT_DIR"], "src", "web_index.h")

data = gzip.compress(open(src, "rb").read(), 9, mtime=0)
lines = ["// generated by esp32common/web/build_web.py from esp32common/web/index.html, do not edit", "",
         "#pragma once", "", "#include <Arduino.h>", "",
         "static const uint8_t web_index_gz[] PROGMEM = {"]
for i in range(0, len(data), 24):
    lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"

if not os.path.exists(dst) or open(dst).read() != text:
    open(dst, "w", newline="\n").write(text)
    print("web/index.html: %d bytes gzipped" % len(data))
